"""Writes docs/RULES_V2.md and frontend/src/data/rules.json from the contracts
themselves: the registries and bounds are read from the loaded module, every
refusal code with its message is read from the source, and the functions that
decide money are quoted verbatim. Nothing in these two files is typed by hand.
    python3 tools/rules_md.py           write both files
    python3 tools/rules_md.py --check   exit 1 if either is stale
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "test" / "v2"))
import stub  # noqa: E402

stub._install_stub()
SRC = (ROOT / "contracts" / "MakeWholeV2.py").read_text()
GATE_SRC = (ROOT / "contracts" / "RecoveryGate.py").read_text()
MW = stub.load_full(ROOT / "contracts" / "MakeWholeV2.py", "MakeWholeV2")
GATE = stub.load_full(ROOT / "contracts" / "RecoveryGate.py", "RecoveryGate")

QUOTED = ["entitled", "compute_owed", "judge", "reconcile", "cond_holds", "quorum"]
GATE_QUOTED = ["classify"]


def fn_source(src, name):
    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return ast.get_source_segment(src, node)
    raise KeyError(name)


def refusals():
    """code -> first message text after it, from every raise / refuse in the source."""
    out = {}
    for m in re.finditer(r'(?:UserError\(|"refuse": )"([A-Z_]+): ([^"]*)"', SRC):
        out.setdefault(m.group(1), m.group(2).strip())
    return dict(sorted(out.items()))


def formulas():
    out = {}
    for m in re.finditer(r'^F_[A-Z_]+ = "([A-Z_]+)"\s+# (.+)$', SRC, re.M):
        out[m.group(1)] = m.group(2).strip()
    return out


def gate_states():
    block = GATE_SRC[GATE_SRC.find("#   NO_INCIDENT"):GATE_SRC.find("# NEVER FAVOURABLE")]
    out = {}
    cur = None
    for line in block.splitlines():
        t = line[1:].strip() if line.startswith("#") else ""
        m = re.match(r"([A-Z_]+)\s{2,}(.*)", t)
        if m and m.group(1) in GATE.STATES:
            cur = m.group(1)
            out[cur] = m.group(2)
        elif cur and t:
            out[cur] += " " + t
    return out


def data():
    return {
        "version": MW.VERSION,
        "chains": {str(k): v for k, v in MW.CHAINS.items()},
        "templates": {t: {"event": MW.TEMPLATE_EVENTS[t], "topic0": MW.TOPICS[t], "formulas": list(MW.FORMULAS_FOR[t])} for t in MW.TOPICS},
        "emitters": {t: {str(c): m for c, m in MW.EMITTERS[t].items()} for t in MW.EMITTERS},
        "comet_base_tokens": MW.COMET_BASE,
        "formulas": formulas(),
        "verdict_reasons": [MW.R_COLLATERAL, MW.R_DEBT, MW.R_PRICE, MW.R_MIN],
        "reconciliation": [MW.REC_MATCH, MW.REC_DIFF, MW.REC_NOT_IN_LIST],
        "payout_kinds": [MW.P_CLAIM, MW.P_SURPLUS, MW.P_CLOSE, MW.P_REFUSED],
        "cond_ops": list(MW.COND_OPS),
        "refusals": refusals(),
        "gate_states": gate_states(),
        "bounds": {k: getattr(MW, k) for k in ("MIN_SOURCES", "MAX_RPCS", "MAX_EMITTERS", "MAX_MARKETS", "MAX_ASSETS",
                                               "MAX_LIST", "MAX_PAGE", "MAX_BLOCK_SPAN", "MAX_WINDOW_S", "MIN_TERMS", "MAX_TERMS")},
        "code": {n: fn_source(SRC, n) for n in QUOTED},
        "gate_code": {n: fn_source(GATE_SRC, n) for n in GATE_QUOTED},
        "header": SRC[SRC.find("# MakeWhole v2"):SRC.find("VERSION =")].rstrip(),
    }


def markdown(d):
    L = ["# MakeWhole v2: the rules, as the code has them", "",
         "Generated by `tools/rules_md.py` from `contracts/MakeWholeV2.py` and `contracts/RecoveryGate.py` "
         "(version " + d["version"] + "). The test suite regenerates this file and fails if it differs.", "",
         "## The contract's own summary", "", "```", d["header"], "```", "",
         "## Chains that count", "", "| chain id | name |", "|---|---|"]
    L += ["| %s | %s |" % (k, v) for k, v in d["chains"].items()]
    L += ["", "## Event templates", "", "| template | event | topic0 | formulas allowed |", "|---|---|---|---|"]
    L += ["| %s | `%s` | `%s` | %s |" % (t, v["event"], v["topic0"], ", ".join(v["formulas"])) for t, v in d["templates"].items()]
    L += ["", "## Official emitters", "", "A log counts only if one of these addresses emitted it.", "",
          "| template | chain | address | label |", "|---|---|---|---|"]
    for t, by in d["emitters"].items():
        for c, m in by.items():
            for a, lab in m.items():
                L.append("| %s | %s | `%s` | %s |" % (t, c, a, lab))
    L += ["", "Compound v3 base tokens (the debt asset of every absorb in that market):", "", "| comet | base token |", "|---|---|"]
    L += ["| `%s` | `%s` |" % (k, v) for k, v in d["comet_base_tokens"].items()]
    L += ["", "## Formulas", "", "| formula | amount (reference wei) |", "|---|---|"]
    L += ["| %s | `%s` |" % (k, v) for k, v in d["formulas"].items()]
    L += ["", "## Refusals (nothing is recorded)", "", "| code | message |", "|---|---|"]
    L += ["| %s | %s |" % (k, v.replace("|", "\\|")) for k, v in d["refusals"].items()]
    L += ["", "## Recorded as NOT_ELIGIBLE (counted once, owed 0)", ""] + ["- `%s`" % r for r in d["verdict_reasons"]]
    L += ["", "## Reconciliation states", ""] + ["- `%s`" % r for r in d["reconciliation"]]
    L += ["", "## Payout kinds (every value message the contract sends)", ""] + ["- `%s`" % r for r in d["payout_kinds"]]
    L += ["", "## Price-source comparison operators", "", ", ".join("`%s`" % o for o in d["cond_ops"])]
    L += ["", "## RecoveryGate states", "", "| state | meaning |", "|---|---|"]
    L += ["| %s | %s |" % (k, v) for k, v in d["gate_states"].items()]
    L += ["", "## Bounds", "", "| name | value |", "|---|---|"]
    L += ["| %s | %s |" % (k, v) for k, v in d["bounds"].items()]
    L += ["", "## The functions that decide money, verbatim", ""]
    for n, s in list(d["code"].items()) + list(d["gate_code"].items()):
        L += ["### `%s`" % n, "", "```python", s, "```", ""]
    return "\n".join(L).rstrip() + "\n"


def outputs():
    d = data()
    return {ROOT / "docs" / "RULES_V2.md": markdown(d),
            ROOT / "frontend" / "src" / "data" / "rules.json": json.dumps(d, indent=1, sort_keys=True) + "\n"}


if __name__ == "__main__":
    bad = 0
    for path, text in outputs().items():
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                print("STALE", path.relative_to(ROOT))
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print("wrote", path.relative_to(ROOT), len(text), "bytes")
    sys.exit(1 if bad else 0)
